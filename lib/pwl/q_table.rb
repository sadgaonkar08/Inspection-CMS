    def self.lookup(q, n)
      raise ArgumentError, "n=#{n} outside supported range 3..10" unless SUPPORTED_N.include?(n)

      return 0 if q < threshold(1, n)
      (1..99).each do |pwl|
        return pwl if q <= threshold(pwl, n)
      end
      100
    end

    def self.threshold(pwl, n)
      pwl >= 50 ? POSITIVE.fetch(pwl).fetch(n) : -POSITIVE.fetch(100 - pwl).fetch(n)
    end
